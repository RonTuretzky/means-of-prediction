#!/usr/bin/env node
// Copies contract ABIs (from forge artifacts) and deployed addresses (from
// deployments/*.json) into src/contracts/gen.ts so the app never drifts from the
// compiled contracts. Run automatically by `npm run dev` / `build`.
//
// Embeds EVERY real-network deployment (gnosis, sepolia) so the served app can
// switch networks at runtime, plus whichever network DEPLOYMENT selects as the
// default (local anvil during dev).
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const out = (name) =>
  JSON.parse(readFileSync(join(root, "contracts", "out", `${name}.sol`, `${name}.json`), "utf8")).abi;

// DEPLOYMENT=gnosis|sepolia|local (default local) picks the app's default network.
const defaultNetwork = process.env.DEPLOYMENT ?? "local";
const REAL_NETWORKS = ["gnosis", "sepolia"];

const deployments = {};
for (const network of [...new Set([defaultNetwork, ...REAL_NETWORKS])]) {
  const file = join(root, "contracts", "deployments", `${network}.json`);
  if (!existsSync(file)) {
    if (network === defaultNetwork) throw new Error(`missing deployment file for DEPLOYMENT=${network}: ${file}`);
    continue;
  }
  const d = JSON.parse(readFileSync(file, "utf8"));
  // "llmJudge" is optional: deployments without it have factory.judge() == address(0)
  // and the app disables AI-judged market creation for that network.
  if (d.llmJudge === undefined) d.llmJudge = null;
  deployments[network] = d;
}

const abis = {
  MarketFactory: out("MarketFactory"),
  HeadlineMarket: out("HeadlineMarket"),
  FPMM: out("FPMM"),
  ConditionalTokens: out("ConditionalTokens"),
  TestUSDC: out("TestUSDC"),
  DKIMRegistry: out("DKIMRegistry"),
  DKIMVerifier: out("DKIMVerifier"),
  EmailBodyStore: out("EmailBodyStore"),
  LLMJudge: out("LLMJudge"),
};

const ts = `// AUTO-GENERATED by scripts/sync-contracts.mjs — do not edit.
export const defaultNetwork = ${JSON.stringify(defaultNetwork)};

export const deployments = ${JSON.stringify(deployments, null, 2)} as const;

export const abis = ${JSON.stringify(abis, null, 2)} as const;
`;

const dest = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "contracts");
mkdirSync(dest, { recursive: true });
writeFileSync(join(dest, "gen.ts"), ts);
console.log(
  `synced ABIs + deployments [${Object.keys(deployments).join(", ")}] (default ${defaultNetwork}) ->`,
  join(dest, "gen.ts"),
);
